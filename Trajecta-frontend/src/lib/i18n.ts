export function formatDateByLocale(iso: string, locale: Locale): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) {
    return locale === "uk" ? "щойно" : "just now";
  }
  return date.toLocaleString(locale === "uk" ? "uk-UA" : "en-US");
}











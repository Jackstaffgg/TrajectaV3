export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const value = translations[locale]?.[key] ?? translations.en?.[key];
  if (typeof value === "function") {
    return value(params);
  }
  if (typeof value !== "string") {
    return key;
  }

  if (!params) {
    return value;
  }

  return Object.entries(params).reduce(
    (acc, [name, param]) => acc.replace(new RegExp(`\\{${name}\\}`, "g"), String(param)),
    value
  );
}

export function tr(locale: Locale, key: string): string {
  return t(locale, key);
}

export function trFmt(locale: Locale, key: string, params: Record<string, string | number>): string {
  return t(locale, key, params);
}

export function localizeTaskStatus(status: TaskStatus, locale: Locale): string {
  const en: Record<TaskStatus, string> = {
    PENDING: "Pending",
    PROCESSING: "Processing",
    COMPLETED: "Completed",
    FAILED: "Failed",
    CANCELLED: "Cancelled"
  };
  const uk: Record<TaskStatus, string> = {
    PENDING: "Очікування",
    PROCESSING: "Обробка",
    COMPLETED: "Завершено",
    FAILED: "Помилка",
    CANCELLED: "Скасовано"
  };
  if (locale === "uk") {
    return uk[status];
  }
  return en[status];
}

export function localizeNotificationType(type: string, locale: Locale): string {
  const key = `notif.${type.toUpperCase()}`;
  return t(locale, key);
}

export function localizeErrorScope(scope: string | null | undefined, locale: Locale): string | null {
  if (!scope) {
    return null;
  }
  return t(locale, `scope.${scope}`);
}

